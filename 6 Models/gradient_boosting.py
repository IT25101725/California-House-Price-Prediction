import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from google.colab import files

print("Libraries imported successfully!")

uploaded = files.upload()

train_df = pd.read_csv(
    "california_housing_train_PCA.csv"
)

test_df = pd.read_csv(
    "california_housing_test_PCA.csv"
)

print("Training dataset shape:", train_df.shape)
print("Testing dataset shape:", test_df.shape)

display(train_df.head())

print(train_df.info())

X_train = train_df.drop(
    "median_house_value",
    axis=1
)

y_train = train_df["median_house_value"]

X_test = test_df.drop(
    "median_house_value",
    axis=1
)

y_test = test_df["median_house_value"]

print("X_train:", X_train.shape)
print("X_test:", X_test.shape)
print("y_train:", y_train.shape)
print("y_test:", y_test.shape)

# Model 5 — Gradient Boosting

from sklearn.ensemble import GradientBoostingRegressor

gradient_boosting_model = (
    GradientBoostingRegressor(
        n_estimators=100,
        learning_rate=0.1,
        max_depth=3,
        random_state=42
    )
)

gradient_boosting_model.fit(
    X_train,
    y_train
)

print("Gradient Boosting trained successfully!")

gradient_boosting_predictions = (
    gradient_boosting_model.predict(X_test)
)

from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    r2_score
)

gradient_boosting_mae = mean_absolute_error(
    y_test,
    gradient_boosting_predictions
)

gradient_boosting_mse = mean_squared_error(
    y_test,
    gradient_boosting_predictions
)

gradient_boosting_rmse = np.sqrt(
    gradient_boosting_mse
)

gradient_boosting_r2 = r2_score(
    y_test,
    gradient_boosting_predictions
)

print("Gradient Boosting Results")
print("--------------------------------")
print("MAE :", gradient_boosting_mae)
print("MSE :", gradient_boosting_mse)
print("RMSE:", gradient_boosting_rmse)
print("R²  :", gradient_boosting_r2)

plt.figure(figsize=(8, 6))

plt.scatter(
    y_test,
    gradient_boosting_predictions,
    alpha=0.5,
    color="magenta"
)

plt.xlabel("Actual House Value")
plt.ylabel("Predicted House Value")
plt.title("Gradient Boosting: Actual vs Predicted")

plt.show()