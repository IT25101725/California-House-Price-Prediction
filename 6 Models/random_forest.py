import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from google.colab import files

print("Libraries imported successfully!")

uploaded = files.upload()

train_df = pd.read_csv(
    "california_housing_train_PCA.csv"
)

test_df = pd.read_csv(
    "california_housing_test_PCA.csv"
)

print("Training dataset shape:", train_df.shape)
print("Testing dataset shape:", test_df.shape)

display(train_df.head())

print(train_df.info())

X_train = train_df.drop(
    "median_house_value",
    axis=1
)

y_train = train_df["median_house_value"]

X_test = test_df.drop(
    "median_house_value",
    axis=1
)

y_test = test_df["median_house_value"]

print("X_train:", X_train.shape)
print("X_test:", X_test.shape)
print("y_train:", y_train.shape)
print("y_test:", y_test.shape)

#  Model 4 — Random Forest

from sklearn.ensemble import RandomForestRegressor

random_forest_model = RandomForestRegressor(
    n_estimators=100,
    random_state=42,
    n_jobs=-1
)

random_forest_model.fit(
    X_train,
    y_train
)

print("Random Forest trained successfully!")

random_forest_predictions = (
    random_forest_model.predict(X_test)
)

from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    r2_score
)

random_forest_mae = mean_absolute_error(
    y_test,
    random_forest_predictions
)

random_forest_mse = mean_squared_error(
    y_test,
    random_forest_predictions
)

random_forest_rmse = np.sqrt(
    random_forest_mse
)

random_forest_r2 = r2_score(
    y_test,
    random_forest_predictions
)

print("Random Forest Results")
print("--------------------------------")
print("MAE :", random_forest_mae)
print("MSE :", random_forest_mse)
print("RMSE:", random_forest_rmse)
print("R²  :", random_forest_r2)

plt.figure(figsize=(8, 6))

plt.scatter(
    y_test,
    random_forest_predictions,
    alpha=0.5,
    color="Green"
)

plt.xlabel("Actual House Value")
plt.ylabel("Predicted House Value")
plt.title("Random Forest: Actual vs Predicted")

plt.show()