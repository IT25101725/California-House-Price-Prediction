import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from google.colab import files

print("Libraries imported successfully!")

uploaded = files.upload()

train_df = pd.read_csv(
    "california_housing_train_PCA.csv"
)

test_df = pd.read_csv(
    "california_housing_test_PCA.csv"
)

print("Training dataset shape:", train_df.shape)
print("Testing dataset shape:", test_df.shape)

display(train_df.head())

print(train_df.info())

X_train = train_df.drop(
    "median_house_value",
    axis=1
)

y_train = train_df["median_house_value"]

X_test = test_df.drop(
    "median_house_value",
    axis=1
)

y_test = test_df["median_house_value"]

print("X_train:", X_train.shape)
print("X_test:", X_test.shape)
print("y_train:", y_train.shape)
print("y_test:", y_test.shape)

# Model 3 — Decision Tree

from sklearn.tree import DecisionTreeRegressor

decision_tree_model = DecisionTreeRegressor(
    max_depth=20,
    random_state=42
)

decision_tree_model.fit(
    X_train,
    y_train
)

print("Decision Tree trained successfully!")

decision_tree_predictions = (
    decision_tree_model.predict(X_test)
)

from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    r2_score
)

decision_tree_mae = mean_absolute_error(
    y_test,
    decision_tree_predictions
)

decision_tree_mse = mean_squared_error(
    y_test,
    decision_tree_predictions
)

decision_tree_rmse = np.sqrt(
    decision_tree_mse
)

decision_tree_r2 = r2_score(
    y_test,
    decision_tree_predictions
)

print("Decision Tree Results")
print("--------------------------------")
print("MAE :", decision_tree_mae)
print("MSE :", decision_tree_mse)
print("RMSE:", decision_tree_rmse)
print("R²  :", decision_tree_r2)

plt.figure(figsize=(8, 6))

plt.scatter(
    y_test,
    decision_tree_predictions,
    alpha=0.5
)

plt.xlabel("Actual House Value")
plt.ylabel("Predicted House Value")
plt.title("Decision Tree: Actual vs Predicted")

plt.show()